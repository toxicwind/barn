#!/usr/bin/env bun
// name-fix.ts — Estate name fixer: check availability, generate pairs, rename.
//
// Chains name-check into rename-roundup so a rebrand is one command:
//
//   bun run bin/name-fix.ts <old-name> <new-name> --repo <git-root> [--execute] [--dry-run-only]
//
// Pipeline:
//   1. checkName(new-name)           — abort on conflicts (candidate taken)
//   2. auto-generate pairs file      — case variants + separator compounds
//      (word rules for bare tokens; substr for _ - / . compounds, since \b
//      does not split on separators — the flock_state.db lesson)
//   3. rename.ts --dry-run           — show the blast radius
//   4. --execute: rename.ts --commit — apply + commit (rollback: reset HEAD~1)
//
// The pairs generator derives everything mechanically from old/new — no
// hand-written pairs files again.

import { $ } from "bun";
import { checkName } from "./name-check.ts";

const ESTATE = "/home/toxic/estate";
const RENAME_TS = `${ESTATE}/skills/rename-roundup/rename.ts`;

interface CaseVariants {
	lower: string;
	Upper: string;
	UPPER: string;
}

function variants(name: string): CaseVariants {
	// word tokens: "feedlot" -> lower/Upper/UPPER; kebab compounds get per-part casing
	const parts = name.split("-");
	const Upper = parts.map((p) => p[0].toUpperCase() + p.slice(1)).join("-");
	const UPPER = parts.map((p) => p.toUpperCase()).join("-");
	return { lower: name.toLowerCase(), Upper, UPPER: name.toUpperCase() === name ? name : UPPER };
}

// Compound forms appear inside identifiers joined by separators. \b word rules
// cannot match them (underscore is a word char), so each separator family gets
// a substr rule.
function compoundPairs(oldN: CaseVariants, newN: CaseVariants): string[] {
	const seps = ["_", "-", "/", "."];
	const rules: string[] = [];
	for (const sep of seps) {
		rules.push(`substr: ${oldN.lower}${sep} => ${newN.lower}${sep}`);
		rules.push(`substr: ${oldN.UPPER}${sep} => ${newN.UPPER}${sep}`);
		rules.push(`substr: ${oldN.Upper}${sep} => ${newN.Upper}${sep}`);
		// leading separator: paths like /flock, -flock in dash-compounds
		rules.push(`substr: ${sep}${oldN.lower} => ${sep}${newN.lower}`);
		rules.push(`substr: ${sep}${oldN.UPPER} => ${sep}${newN.UPPER}`);
	}
	return rules;
}

function generatePairs(oldName: string, newName: string): string {
	const o = variants(oldName);
	const n = variants(newName);
	const lines = [
		`# Auto-generated by bin/name-fix.ts — ${oldName} -> ${newName}`,
		`# Generated: ${new Date().toISOString()}`,
		"",
		"# Bare tokens (word boundary, case variants)",
		`word: ${o.lower} => ${n.lower}`,
		`word: ${o.Upper} => ${n.Upper}`,
		`word: ${o.UPPER} => ${n.UPPER}`,
		"",
		"# Separator compounds (substr — \\b does not split on _ - / .)",
		...compoundPairs(o, n),
		"",
		"# Daemon id forms",
		`substr: daemons.${o.lower} => daemons.${n.lower}`,
		`substr: estate/${o.lower} => estate/${n.lower}`,
	];
	return lines.join("\n") + "\n";
}

async function main(): Promise<void> {
	const args = process.argv.slice(2);
	const oldName = args[0];
	const newName = args[1];
	const repoIdx = args.indexOf("--repo");
	const repo = repoIdx >= 0 ? args[repoIdx + 1] : `${ESTATE}`;
	const execute = args.includes("--execute");
	const dryRunOnly = args.includes("--dry-run-only");
	const force = args.includes("--force");

	if (!oldName || !newName) {
		console.error(
			"Usage: bun run bin/name-fix.ts <old-name> <new-name> [--repo <git-root>] [--execute] [--dry-run-only]",
		);
		process.exit(1);
	}
	if (oldName === newName) {
		console.error("old and new names are identical");
		process.exit(1);
	}

	// 1. Availability gate on the NEW name.
	console.log(`── 1/3 availability check: '${newName}'`);
	const check = await checkName(newName);
	// Conflicts inside the target repo itself are expected (the thing being renamed).
	const repoPrefix = repo.replace(/\/$/, "") + "/";
	const external = check.conflicts.filter((c) => !c.match.startsWith(repoPrefix));
	if (external.length > 0 && !force) {
		console.error(`❌ '${newName}' is taken outside the target repo:`);
		for (const c of external.slice(0, 15)) console.error(`   ${c.source}: ${c.match}`);
		console.error("Aborting — pick a free name (bin/name-check.ts <candidate>). Pass --force to override (re-runs).");
		process.exit(1);
	}
	if (external.length > 0) console.log(`⚠️ --force: ${external.length} external conflict(s) overridden`);
	console.log(`✅ free (conflicts limited to the target repo: ${check.conflicts.length})`);

	// 2. Generate pairs file.
	const pairsPath = `${ESTATE}/docs/name-fix-${oldName}-to-${newName}.pairs`;
	await Bun.write(pairsPath, generatePairs(oldName, newName));
	console.log(`── 2/3 pairs generated: ${pairsPath}`);

	// 3. Dry-run, then optionally execute.
	console.log(`── 3/3 rename dry-run on ${repo}`);
	const dry = await $`bun run ${RENAME_TS} --repo ${repo} --pairs ${pairsPath} --dry-run`.nothrow().quiet();
	console.log(dry.stdout.toString());
	if (dry.exitCode !== 0) {
		console.error(dry.stderr.toString());
		process.exit(1);
	}

	if (dryRunOnly) {
		console.log("dry-run-only: stopping before execute.");
		return;
	}
	if (!execute) {
		console.log("Dry run complete. Re-run with --execute to apply + commit.");
		return;
	}

	const commitMsg = `rename: ${oldName} -> ${newName} (name-fix: check → pairs → rename)`;
	const run = await $`bun run ${RENAME_TS} --repo ${repo} --pairs ${pairsPath} --commit ${commitMsg}`
		.nothrow()
		.quiet();
	console.log(run.stdout.toString());
	if (run.exitCode !== 0) {
		console.error(run.stderr.toString());
		process.exit(1);
	}
	console.log(`✅ renamed '${oldName}' -> '${newName}' and committed. rollback: git -C ${repo} reset --hard HEAD~1`);
}

main();
