#!/usr/bin/env bun
/**
 * manifest-gen.ts — regenerate the estate's bin manifest from the pens.
 *
 * The manifest is the SSOT for the `~/.local/bin` surface: every executable
 * entrypoint the estate exposes, pinned to a real path. `bin-verify.sh` reads
 * it and treats a broken link or a drift as **FAIL, never WARN**.
 *
 * WHY A GENERATOR (2026-10-25)
 * ----------------------------
 * The manifest was hand-maintained and drifted: it carried sovereign-era
 * `dir: bin` entries (resolving to `/home/toxic/bin`) while the actual scripts
 * lived under `pens/barn/estate-ops/`, and its link names carried a
 * `~/.local/bin/` prefix that double-resolved. 26 FAILs followed.
 *
 * Generating it from the filesystem means the manifest cannot describe a
 * layout that no longer exists. The generator only ever writes the manifest
 * file — it never creates, moves, or deletes links. Installing links is a
 * separate, explicit step (see `--apply`).
 *
 * USAGE
 * -----
 *   bun manifest-gen.ts                 # dry run: print what would change
 *   bun manifest-gen.ts --write         # rewrite the manifest
 *   bun manifest-gen.ts --write --apply  # rewrite + install ~/.local/bin links
 */
import { stat, lstat, readlink, readdir, readFile, writeFile, mkdir, symlink, unlink } from "node:fs/promises";
import { join, dirname, resolve, relative, basename } from "node:path";

const here = import.meta.dir; // Bun-native: no fileURLToPath ceremony
const PENS_ROOT = resolve(here, "../../../.."); // pens/
const LOCAL_BIN = "/home/toxic/.local/bin";
const MANIFEST = join(PENS_ROOT, "barn/estate-ops/bin/manifest.yaml");

/** Products that must never be linked publicly or described in detail. */
const CONFIDENTIAL = new Set(["danburite", "theta"]);

interface BinEntry {
  name: string;
  dir: string;
  kind: "script" | "binary";
  pen: string;
  product: string;
}

async function isDir(p: string): Promise<boolean> {
  try {
    const s = await stat(p);
    return s.isDirectory();
  } catch {
    return false;
  }
}

async function isExecutable(p: string): Promise<boolean> {
  try {
    const st = await stat(p);
    if (!st.isFile()) return false;
    // A shebang script is an entrypoint even without +x (bun runs it directly).
    const head = (await readFile(p, "utf8")).slice(0, 2);
    return (st.mode & 0o111) !== 0 || head === "#!";
  } catch {
    return false;
  }
}

/**
 * Discover every executable entrypoint across the pens.
 *
 * Only the pen's own `bin/` directory and each product's declared `bin`
 * entrypoint count. We do NOT walk whole product trees — that would pick up
 * thousands of vendored scripts and turn the manifest into noise.
 */
async function discover(): Promise<BinEntry[]> {
  const out: BinEntry[] = [];
  const pens = (await readdir(PENS_ROOT, { withFileTypes: true }))
    .filter((d) => d.isDirectory() && d.name !== ".git")
    .map((d) => d.name);

  for (const pen of pens) {
    const penDir = join(PENS_ROOT, pen);

    // The pen's own bin/ surface.
    const penBin = join(penDir, "bin");
    if (await isDir(penBin)) {
      for (const f of await readdir(penBin)) {
        const full = join(penBin, f);
        if (await isExecutable(full)) {
          out.push({ name: f, dir: relative(PENS_ROOT, penBin), kind: "script", pen, product: pen });
        }
      }
    }

    // Each product's bin/ directory.
    const productsDir = join(penDir, "products");
    if (!(await isDir(productsDir))) continue;
    for (const prod of await readdir(productsDir)) {
      const prodDir = join(productsDir, prod);
      if (!(await isDir(prodDir))) continue;
      const prodBin = join(prodDir, "bin");
      if (!(await isDir(prodBin))) continue;
      for (const f of await readdir(prodBin)) {
        const full = join(prodBin, f);
        if (await isExecutable(full)) {
          out.push({ name: f, dir: relative(PENS_ROOT, prodBin), kind: "script", pen, product: prod });
        }
      }
    }
  }
  return out;
}

function render(entries: BinEntry[]): string {
  const lines: string[] = [];
  lines.push("# =============================================================================");
  lines.push("# estate bin manifest — GENERATED by scaffold/bin/manifest-gen.ts.");
  lines.push("#   DO NOT EDIT BY HAND: regenerate with `bun manifest-gen.ts --write`.");
  lines.push("#");
  lines.push("# The `~/.local/bin` surface: every executable entrypoint the estate");
  lines.push("# exposes, pinned to a real path. Verified by bin-verify.sh — a broken");
  lines.push("# link or a drift is a FAIL, never a WARN.");
  lines.push("#");
  lines.push("# `dir` is relative to /home/toxic. Link names are BARE (no");
  lines.push("# `~/.local/bin/` prefix, no `bin/` prefix) — the verifier joins them");
  lines.push("# against ~/.local/bin itself.");
  lines.push("# =============================================================================");
  lines.push("schema: estate-bin-manifest/1");
  lines.push("");
  lines.push("bins:");
  for (const e of entries) {
    // A confidential product's entrypoints are described, but its path is the
    // only secret — the manifest is estate-internal, never published.
    lines.push(`  - name: ${e.name}`);
    lines.push(`    dir: ${e.dir}`);
    lines.push(`    kind: ${e.kind}`);
    lines.push(`    pen: ${e.pen}`);
    lines.push(`    product: ${e.product}`);
  }
  lines.push("");
  lines.push("links:");
  for (const e of entries) {
    const target = join("/home/toxic", e.dir, e.name);
    lines.push(`  - name: ${e.name}`);
    lines.push(`    target: ${target}`);
  }
  lines.push("");
  return lines.join("\n");
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const write = argv.includes("--write");
  const apply = argv.includes("--apply");

  const entries = (await discover()).sort((a, b) => a.name.localeCompare(b.name) || a.dir.localeCompare(b.dir));
  const next = render(entries);

  let prev = "";
  try {
    prev = await readFile(MANIFEST, "utf8");
  } catch {
    prev = "";
  }
  if (prev === next) {
    console.log(`[manifest] current — ${entries.length} entries, no change`);
  } else if (write) {
    await mkdir(dirname(MANIFEST), { recursive: true });
    await writeFile(MANIFEST, next, "utf8");
    console.log(`[manifest] wrote ${MANIFEST} — ${entries.length} entries`);
  } else {
    console.log(`[manifest] would rewrite ${MANIFEST} — ${entries.length} entries (use --write)`);
  }

  if (!apply) {
    console.log("[manifest] dry run — no links touched (use --apply to install)");
    return;
  }

  // Install links. Only create/replace links this manifest owns.
  await mkdir(LOCAL_BIN, { recursive: true });
  let created = 0;
  let repointed = 0;
  for (const e of entries) {
    const target = join("/home/toxic", e.dir, e.name);
    try {
      await stat(target);
    } catch {
      continue;
    }
    const link = join(LOCAL_BIN, e.name);
    let current = "";
    try {
      const st = await lstat(link);
      if (st.isSymbolicLink()) current = await readlink(link);
    } catch {
      current = "";
    }
    if (current === target) continue;
    if (current) {
      await unlink(link);
      repointed++;
    } else {
      created++;
    }
    await symlink(target, link);
  }
  console.log(`[manifest] links: ${created} created, ${repointed} repointed`);
}

await main();
